def test_visa_and_kraft_heinz_put_the_timing_in_the_sentence_after_the_date():
    v = ("Visa to Announce Fiscal Fourth Quarter and Full-Year 2026 Financial Results on October 27, 2026. SAN FRANCISCO, October 08, 2026--Visa "
         "(NYSE: V) will report its fiscal fourth quarter and full-year 2026 financial results on Tuesday, October 27, 2026. After market close, Visa "
         "will furnish the results with the Securities and Exchange Commission and post them, along with accompanying financial information, on the "
         "Visa Investor Relations website.")
    hit = R.read_release_date(v, TODAY)
    assert (hit.day, hit.timing) == (date(2026, 10, 27), "unknown")         # the headline is the first release sentence; the body's comes next
    body = R.read_release_date(v.split(". ", 1)[1], TODAY)
    assert (body.day, body.timing) == (date(2026, 10, 27), "amc")
    # the model quoted the timing sentence (2026-10-26 nightly: "quote does not name 2026-10-27"); with the date sentence before it, it stands
    model = {"date": date(2026, 10, 27), "timing": "amc", "quote": "After market close, Visa will furnish the results with the Securities and Exchange "
             "Commission and post them, along with accompanying financial information, on the Visa Investor Relations website."}
    assert R.decide(body, model, v, TODAY)[0] == date(2026, 10, 27)
    khc = ("The Kraft Heinz Company (NYSE: KHC) (\"Kraft Heinz\") will release its third quarter 2026 financial results on Wednesday, Nov. 4, 2026. "
           "A press release and supplemental materials, including a pre-recorded management discussion, will be issued before the market opens.")
    hit = R.read_release_date(khc, TODAY)
    assert (hit.day, hit.timing) == (date(2026, 11, 4), "bmo")
    model = {"date": date(2026, 11, 4), "timing": "bmo", "quote": "A press release and supplemental materials, including a pre-recorded management "
             "discussion, will be issued before the market opens."}
    assert R.decide(hit, model, khc, TODAY)[0] == date(2026, 11, 4)
    # a quote from somewhere else in the text still fails
    far = {**model, "quote": "Kraft Heinz management will then host a live question-and-answer session."}
    assert R.decide(hit, far, khc + " Kraft Heinz management will then host a live question-and-answer session.", TODAY)[0] is None


