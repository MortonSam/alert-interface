"""Why the reader missed company-announced dates for the largest S&P 500 names (Sam, 2026-10-26), as worked examples from the
companies' own words. Production's ir_feeds table was empty, so no IR feed was ever read there; Q4-hosted companies keep their
results on an events feed (/rss/event.aspx) the reader never read; and four wording rules turned company releases away."""
from datetime import date

from app.scripts import confirm_report_dates as C
from app.services import ir_feeds as F
from app.services import report_date_reader as R

TODAY = date(2026, 10, 26)


def read(kind, text, symbol):
    hit = R.read_release_date(text, TODAY) or R.read_report_date(text, TODAY)
    assert hit is not None, text
    return R.classify_quote(kind, text, hit.sentence, hit.day, symbol, TODAY), hit.day, hit.timing


# Apple's events feed as it read on 2026-10-26: Apple issues no press release for its date; its IR calendar names the results event
APPLE_EVENTS = """<?xml version="1.0" encoding="utf-8"?><rss version="2.0"><channel><title>Apple Events  </title><link>https://investor.apple.com/</link>
<description>generated by Q4</description><lastBuildDate>Mon, 02 Nov 2026 14:00:00 -0500</lastBuildDate><item><title>11/2/2026 : FY 26 Fourth Quarter Results</title>
<description>&lt;span&gt;&lt;p&gt;Apple’s conference call to discuss fourth quarter results and business updates is scheduled for Monday, November 2, 2026
at 2:00 p.m. PT / 5:00 p.m. ET. &lt;/p&gt;&lt;/span&gt;</description><link>https://investor.apple.com/event-details/2026/FY-26-Fourth-Quarter-Results/default.aspx</link>
<pubDate>Tue, 06 Oct 2026 17:09:11 -0400</pubDate></item></channel></rss>"""
NVIDIA_EVENTS = """<?xml version="1.0" encoding="utf-8"?><rss version="2.0"><channel><title>NVIDIA Corporation Events  </title><link>https://investor.nvidia.com/</link>
<description>generated by Q4</description><lastBuildDate>Mon, 01 Jan 0001 00:00:00 -0500</lastBuildDate></channel></rss>"""


def test_apple_names_its_results_on_its_own_events_feed():
    events = F.earnings_events(F.parse_items(APPLE_EVENTS, "https://investor.apple.com/rss/event.aspx"), TODAY)
    assert [(e["day"], e["title"]) for e in events] == [(date(2026, 11, 2), "FY 26 Fourth Quarter Results")]
    assert F.results_event("FY 26 Fourth Quarter Results") and F.results_event("3rd Quarter 2026 Earnings") and F.results_event("Q1 2027 Earnings Results")
    # a call or webcast on the calendar is not the results: its event page is read instead (Sam, 2026-10-20)
    for title in ("Q3 2026 Earnings Conference Call", "2026 Q3 Earnings Call", "Disney’s Q4 FY26 Earnings Results Webcast", "Ecolab Q3 2026 Earnings Release Call"):
        assert not F.results_event(title), title
    assert R.timing_of("is scheduled for Monday, November 2, 2026 at 2:00 p.m. PT / 5:00 p.m. ET.") == "amc"
    note = C.events_note({**events[0]})
    assert note.startswith("confirmed: events feed via IR 2026-11-02: FY 26 Fourth Quarter Results https://investor.apple.com/")
    from app.services.earnings_calendar import company_confirmed
    assert company_confirmed(True, note)


def test_nvidia_has_announced_nothing_and_its_call_notice_would_not_confirm():
    # NVIDIA's events feed on 2026-10-26 is empty, and nothing in its 8-Ks or the wire names a date: Nov 17 is a vendor's estimate
    assert F.earnings_events(F.parse_items(NVIDIA_EVENTS, ""), TODAY) == []
