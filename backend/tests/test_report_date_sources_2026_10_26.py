def test_nvidias_two_day_listing_is_an_expected_day_never_a_confirmation():
    # Sam (2026-10-27): the company's own calendar lists its results over two days with no time: the expected-around day, still not
    # confirmed. The single-date parser never confirms it.
    items = F.parse_items(NVIDIA_LISTING, "https://investor.nvidia.com/rss/event.aspx")
    assert F.earnings_events(items, TODAY) == []
    listings = F.calendar_listings(items, TODAY)
    assert [(x["start"], x["end"], x["day"], x["title"]) for x in listings] == \
        [(date(2026, 11, 16), date(2026, 11, 17), date(2026, 11, 17), "NVIDIA 3rd Quarter FY27 Financial Results")]
    assert F.calendar_listings(F.parse_items(NVIDIA_LISTING.replace("11/16/2026 - 11/17/2026", "11/10/2026 - 11/17/2026"), ""), TODAY) == []   # a week is no report day
    assert F.calendar_listings(F.parse_items(NVIDIA_LISTING.replace("Financial Results", "Financial Results Conference Call"), ""), TODAY) == []   # a call
    from app.services.next_earnings import CALENDAR_SOURCE, expected_window_line
    assert expected_window_line(date(2026, 11, 17), CALENDAR_SOURCE, "NVIDIA") == \
        "Next report expected around Nov 17, 2026, per NVIDIA's events calendar (exact date and time not yet announced)"
    assert expected_window_line(date(2026, 11, 18)) == \
        "Next report expected around Nov 18, 2026, based on its past report dates (not yet confirmed by the company)"


@pytest.mark.asyncio
async def test_the_calendar_day_takes_the_windows_place_on_every_page():
    import json
    from types import SimpleNamespace
    from app.scripts.confirm_report_dates import CALENDAR_KEY
    from app.services import next_earnings as NE
    rows = {CALENDAR_KEY.format(sym="NVDA"): json.dumps({"day": "2026-11-17", "start": "2026-11-16", "end": "2026-11-17", "title": "x", "link": "", "seen_on": "2026-10-27"}),
            "expected_report_window:NVDA": json.dumps({"start": "2026-11-17", "end": "2026-11-19", "center": "2026-11-18", "source": "filings",
                                                     "computation_version": __import__("app.services.report_windows", fromlist=["x"]).WINDOW_VERSION})}

    class Session:
        async def execute(self, *a, **k):
            return SimpleNamespace(all=lambda: list(rows.items()))
    out = {1: NE.NextEarnings()}
    await NE.attach_windows(Session(), out, {1: "NVDA"}, date(2026, 10, 27), {1: "NVIDIA Corporation"})
    ne = out[1]
    assert (ne.confirmation, ne.window_center, ne.window_source, ne.window_company) == (NE.EXPECTED_WINDOW, date(2026, 11, 17), NE.CALENDAR_SOURCE, "NVIDIA")
    rows.pop(CALENDAR_KEY.format(sym="NVDA"))
    out = {1: NE.NextEarnings()}
    await NE.attach_windows(Session(), out, {1: "NVDA"}, date(2026, 10, 27))
    assert out[1].window_center == date(2026, 11, 18)                  # without it, the window from past report dates
