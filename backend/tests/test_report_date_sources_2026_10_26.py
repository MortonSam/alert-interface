def test_visa_and_kraft_heinz_put_the_timing_in_the_sentence_after_the_date():
    v = ("Visa to Announce Fiscal Fourth Quarter and Full-Year 2026 Financial Results on October 27, 2026. SAN FRANCISCO, October 08, 2026--Visa "
         "(NYSE: V) will report its fiscal fourth quarter and full-year 2026 financial results on Tuesday, October 27, 2026. After market close, Visa "
         "will furnish the results with the Securities and Exchange Commission and post them, along with accompanying financial information, on the "
         "Visa Investor Relations website.")
    hit = R.read_release_date(v, TODAY)
    assert (hit.day, hit.timing) == (date(2026, 10, 27), "unknown")         # the headline is the first release sentence; the body's comes next
    body = R.read_release_date(v.split(". ", 1)[1], TODAY)
    assert (body.day, body.timing) == (date(2026, 10, 27), "amc")
    # the model quoted the timing sentence (2026-10-26 nightly: "quote does not name 2026-10-27"); with the date sentence before it, it stands
    model = {"date": date(2026, 10, 27), "timing": "amc", "quote": "After market close, Visa will furnish the results with the Securities and Exchange "
             "Commission and post them, along with accompanying financial information, on the Visa Investor Relations website."}
    assert R.decide(body, model, v, TODAY)[0] == date(2026, 10, 27)
    khc = ("The Kraft Heinz Company (NYSE: KHC) (\"Kraft Heinz\") will release its third quarter 2026 financial results on Wednesday, Nov. 4, 2026. "
           "A press release and supplemental materials, including a pre-recorded management discussion, will be issued before the market opens.")
    hit = R.read_release_date(khc, TODAY)
    assert (hit.day, hit.timing) == (date(2026, 11, 4), "bmo")
    model = {"date": date(2026, 11, 4), "timing": "bmo", "quote": "A press release and supplemental materials, including a pre-recorded management "
             "discussion, will be issued before the market opens."}
    assert R.decide(hit, model, khc, TODAY)[0] == date(2026, 11, 4)
    # a quote from somewhere else in the text still fails
    far = {**model, "quote": "Kraft Heinz management will then host a live question-and-answer session."}
    assert R.decide(hit, far, khc + " Kraft Heinz management will then host a live question-and-answer session.", TODAY)[0] is None


def test_company_releases_on_their_own_feeds():
    amd = "AMD to Report Fiscal Third Quarter 2026 Financial Results. AMD will report its fiscal third quarter 2026 financial results after the market close on Tuesday, November 3, 2026."
    assert read("IR feed", amd, "AMD") == ("release", date(2026, 11, 3), "amc")
    ba = "Boeing to Release Third Quarter Results on October 27."
    assert read("IR feed", ba, "BA")[:2] == ("release", date(2026, 10, 27))
    duk = "Duke Energy to announce third-quarter 2026 financial results on Nov. 5"
    assert read("IR events", duk, "DUK")[:2] == ("release", date(2026, 11, 5))
    # Alphabet's own notice names only its 4:30pm call: estimated, like Booking's (test_report_date_classes)
    googl = ("Alphabet Inc. (NASDAQ: GOOG, GOOGL) will hold its quarterly conference call to discuss third quarter 2026 financial results on "
             "Wednesday, October 28, at 1:30pm Pacific Time (4:30pm Eastern Time).")
    assert read("IR feed", googl, "GOOGL")[0] == "call_only"


def test_previews_stay_someone_elses_words():
    for text_, sym in (("Microsoft (NASDAQ:MSFT) reports fiscal first-quarter results on Wednesday, October 28, after the close.", "MSFT"),
                       ("Gallagher (AJG) is back in focus as the insurer prepares to report fiscal third quarter results on October 29, with analysts expecting more.", "AJG")):
        hit = R.read_report_date(text_, TODAY)
        assert hit is None or R.classify_quote("press release", text_, hit.sentence, hit.day, sym, TODAY) != "release", text_


def test_a_quote_with_no_year_takes_the_coming_date_not_the_models_guess():
    # Boeing on its feed, 2026-10-26: the model returned 2021-10-27 for "on October 27", and the readers disagreed
    ba = "Boeing to Release Third Quarter Results on October 27."
    hit = R.read_release_date(ba, TODAY)
    assert R.decide(hit, {"date": date(2021, 10, 27), "timing": "unknown", "quote": ba}, ba, TODAY)[0] == date(2026, 10, 27)
    # a quote that does give a different year still disagrees
    other = "Boeing will release its third quarter 2027 results on October 27, 2027."
    assert R.decide(hit, {"date": date(2027, 10, 27), "timing": "unknown", "quote": other}, ba + " " + other, TODAY)[0] is None


def test_a_date_two_calendars_agreed_on_takes_the_companys_evidence():
    # Costco, 2026-10-26: stored Dec 10 "confirmed: Finnhub and Yahoo Finance agree"; its events feed names Dec 10. It was "already"
    # confirmed and kept the vendor note, so the page (company-confirmed dates only) still had no date
    vendor = {"event_date": date(2026, 12, 10), "is_confirmed": True, "confirmation_note": "confirmed: Finnhub and Yahoo Finance agree"}
    assert C.classify(date(2026, 12, 10), [vendor])[0] == "confirms"
    assert C.classify(date(2026, 12, 9), [vendor])[0] == "changes"
    company = {**vendor, "confirmation_note": "confirmed: events feed via IR 2026-12-10: Q1 2027 Earnings Results"}
    assert C.classify(date(2026, 12, 10), [company])[0] == "already"
    assert C.classify(date(2026, 12, 9), [company])[0] == "contradicts"


