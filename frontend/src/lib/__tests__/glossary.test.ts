import { readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import GLOSSARY, { explanationOf, variesWithWalkthrough } from "@/lib/glossary";
import { TERMS } from "@/lib/glossaryTerms";
import { explainSegments } from "@/lib/explainSegments";

const SRC = join(__dirname, "../..");
const walk = (dir: string): string[] => readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)]));
const esc = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const exactCase = (v: string) => v === v.toUpperCase() || /[&/]/.test(v);
const found = (v: string, text: string) => new RegExp(`(?<![A-Za-z0-9])${esc(v)}(?![A-Za-z0-9])`, exactCase(v) ? "" : "i").test(text);

describe("the glossary", () => {
  it("explains every term in one or two plain sentences with no other listed term inside", () => {
    expect(TERMS.length).toBeGreaterThanOrEqual(60);
    for (const t of TERMS) {
      const sentences = t.explanation.split(/(?<=[.!?])\s+(?=[A-Z])/);
      expect(sentences.length, t.key).toBeLessThanOrEqual(2);
      expect(t.explanation.split(/\s+/).length, t.key).toBeLessThanOrEqual(45);
      for (const o of TERMS) {
        if (o === t) continue;
        for (const v of o.match) expect(found(v, t.explanation), `${t.key} uses "${v}" (${o.key})`).toBe(false);
      }
      expect(GLOSSARY[t.key], t.key).toBe(t.explanation);
    }
  });
  it("reads its walkthrough form only once the walkthrough is on: Sam's approved text of 2026-11-11, the old Ivy pages' terms retired", () => {
    const held = TERMS.filter((t) => t.walkthrough !== undefined);
    const stays = TERMS.filter((t) => t.walkthrough !== null);
    expect(held.filter((t) => t.walkthrough === null).map((t) => t.key).sort()).toEqual(
      ["backtest", "base-rate", "edge", "exit-rule", "not-priced", "receipt", "receipt-5d-n", "settlement", "setup", "stacking", "too-expensive"]);
    expect(held.filter((t) => t.walkthrough).map((t) => t.key).sort()).toEqual(
      ["assignment", "bid-ask-spread", "bullish-bearish", "early-exercise", "momentum", "slippage", "typical-move-after-reports"]);
    for (const t of held) {
      const aliases = [t.key, t.term, ...t.match];
      for (const a of aliases) expect(variesWithWalkthrough(a), a).toBe(true);
      // "too expensive for the edge" names two terms, both retired; every other name reads its own term
      for (const a of aliases.filter((x) => x.toLowerCase() !== "too expensive for the edge")) {
        expect(explanationOf(a, false), a).toBe(t.explanation);           // nothing changes while the flag is off
        expect(explanationOf(a, true), a).toBe(t.walkthrough);
      }
      if (!t.walkthrough) continue;
      expect(t.walkthrough).not.toMatch(/ledger|Ivy|pick/i);              // the walkthrough has no picks and no ledger
      expect(t.walkthrough.split(/(?<=[.!?])\s+(?=[A-Z])/).length, t.key).toBeLessThanOrEqual(2);
      for (const o of stays) if (o !== t) for (const v of o.match) expect(found(v, t.walkthrough), `${t.key} uses "${v}" (${o.key})`).toBe(false);
    }
    expect(explanationOf("bullish-bearish", true)).toBe("Bullish means a trade that gains if the stock rises; bearish, one that gains if it falls.");
    expect(explanationOf("slippage", true)).toContain("The site's hypothetical results do not include it.");
    expect(explanationOf("receipt", true)).toBeNull();
    expect(explanationOf("too expensive for the edge", true)).toBeNull();
    for (const t of TERMS.filter((x) => x.walkthrough === undefined)) {
      expect(variesWithWalkthrough(t.key), t.key).toBe(false);
      expect(explanationOf(t.key, true), t.key).toBe(t.explanation);
    }
    expect(stays.length).toBeGreaterThanOrEqual(60);
    // one place decides: the tip asks only for a term that differs, and a server page hands its own reading down
    const src = (f: string) => readFileSync(join(SRC, f), "utf8");
    expect(src("components/ticker/ExplainTip.tsx")).toContain("explanationOf(term, useWalkthroughOn(variesWithWalkthrough(term)))");
    expect(src("lib/useIvyMode.ts")).toContain("if (!ask || served !== undefined) return;");
    expect(src("components/WalkthroughText.tsx")).toContain("<IvyFlag.Provider value={on}>{children}</IvyFlag.Provider>");
  });
  it("the Disclosures speak of Ivy's picks and ledger only while the old Ivy pages stand, and keep their tab title", () => {
    const disc = readFileSync(join(SRC, "app/disclosures/page.tsx"), "utf8");
    expect(disc).toContain('title: "Disclosures | Alert Interface"');
    expect(disc).toContain("const walkthrough = await walkthroughOn(API, fetch, 0);");
    expect(disc).toContain("<WalkthroughText on={walkthrough}>");
    const [on1, off1] = disc.split("{walkthrough ? (")[1].split(") : (");
    expect(on1).toContain("Build a Trade drafts are generated by software from public data, and Ivy doesn&apos;t make buy or sell calls.");
    expect(off1.split(")}")[0]).toContain("Ivy's picks and Build a Trade drafts are generated by software from public data <LedgerVisibilityClause />.");
    const [on2, off2] = disc.split("{walkthrough ? (")[2].split(") : (");
    expect(on2).toContain("Trades on this site are hypothetical and never executed. Build a Trade's simulated values and the results of saved trades are computed from published option prices.");
    expect(on2).not.toMatch(/ledger|picks/i);
    expect(off2).toContain("Ivy's ledger tracks picks that were generated and recorded but never executed.");
    expect(off2).toContain("The ledger began {fmtLongDate(start)}");
  });
  it("attaches the explanation to every term in a sentence, longest match first, exact case for acronyms", () => {
    const segs = explainSegments("RV rank 85 of 100, IV rich; one session dominates the 20-day window.");
    expect(segs.filter((s) => s.key).map((s) => [s.text, s.key])).toEqual([["RV rank", "rv-rank"], ["IV rich", "vol-regime"], ["one session dominates the 20-day window", "one-session-dominates"]]);
    expect(explainSegments("the iv of prose").every((s) => !s.key)).toBe(true);
    expect(explainSegments("no terms here").map((s) => s.text).join("")).toBe("no terms here");
  });
});

// Customer-facing text: every page and component except the home page. A term in literal JSX text must sit inside an ExplainTip
// (or reach the page through <Explained text=...>); new jargon can never ship unexplained.
const PAGES = walk(join(SRC, "app")).concat(walk(join(SRC, "components")))
  .filter((f) => f.endsWith(".tsx") && !f.includes("__tests__") && !f.endsWith(join("app", "page.tsx")) && !f.endsWith("Explained.tsx") && !f.includes(join("app", "admin")));

function unexplained(src: string): string[] {
  const stripped = src
    .replace(/<ExplainTip\b[\s\S]*?<\/ExplainTip>/g, " ")               // explained terms
    .replace(/\{\/\*[\s\S]*?\*\/\}/g, " ")                             // JSX comments
    .replace(/<Explained\b[^>]*\/>/g, " ");
  const decode = (t: string) => t.replace(/&apos;/g, "'").replace(/&quot;/g, '"').replace(/&amp;/g, "&").replace(/&lt;/g, "<").replace(/&gt;/g, ">");
  const texts = [...stripped.matchAll(/[>}]([^<>{}]*[A-Za-z][^<>{}]*)[<{]/g)].map((m) => decode(m[1]))   // literal JSX text between tags
    .filter((t) => !/;\s*(\n|$)| = |==|!=|=>|\bconst\b|\breturn\b|\?\.|&&|\|\||\buse[A-Z]|`|^\s*\/\//.test(t));   // not code between a > and a <
  const hits: string[] = [];
  for (const text of texts) for (const t of TERMS) for (const v of t.match) if (found(v, text)) hits.push(`"${v}" in "${text.trim().slice(0, 60)}"`);
  return hits;
}

describe("no term renders without its explanation", () => {
  for (const f of PAGES) {
    it(f.replace(SRC, "src"), () => {
      expect(unexplained(readFileSync(f, "utf8"))).toEqual([]);
    });
  }
});
